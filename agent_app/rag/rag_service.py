def _build_knowledge_base() -> list[Document]:
    """将知识库字典列表转换为 LangChain Document 列表"""
    docs = []
    for item in KNOWLEDGE_BASE:
        doc = Document(
            page_content=item["content"],
            metadata={"source": item["source"]},
        )
        docs.append(doc)
    return docs


def init_knowledge_base():
    """初始化知识库，加载到 ChromaDB 向量存储中"""
    docs = _build_knowledge_base()
    get_vector_store(docs)
    logger.info("知识库已初始化，共加载 %d 条知识", len(docs))


def search_knowledge(query: str) -> str:
    """
    检索本地心理健康知识库。

    该函数是 RAG 工具的核心接口，被 Agent 通过 local_knowledge_search 工具调用。
    与 Agent 完全解耦，可独立测试。

    Args:
        query: 检索关键词或问题

    Returns:
        格式化的知识片段，包含内容和来源标注
    """
    try:
        store = get_vector_store()
        if store is None:
            init_knowledge_base()
            store = get_vector_store()

        retriever = store.as_retriever(search_kwargs={"k": 3})
        docs = retriever.invoke(query)

        if not docs:
            return f"未找到与「{query}」相关的本地知识。建议尝试使用 web_search 搜索外部资源。"

        parts = []
        for i, doc in enumerate(docs, 1):
            source = doc.metadata.get("source", "未知来源")
            parts.append(f"【知识 {i}】\n{doc.page_content}\n（{source}）")

        return "\n\n".join(parts)

    except Exception as e:
        logger.error("知识检索失败: %s", e)
        return f"知识检索出错：{str(e)}。请稍后重试或尝试使用 web_search。"